const Font = (() => {
  const CELL = 6, HEIGHT = 8, COUNT = 95;
  const glyphs = [];
  for (let i = 0; i < COUNT; i++) {
    const cols = FONT_DATA.slice(i * 5, i * 5 + 5);
    let a = 0, b = 4;
    while (a < 4 && cols[a] === 0) a++;
    while (b > a && cols[b] === 0) b--;
    glyphs.push({ cols, a, w: i === 0 ? 3 : b - a + 1 });
  }
  const atlases = {};
  function atlas(color) {
    if (atlases[color]) return atlases[color];
    const c = document.createElement('canvas');
    c.width = CELL * COUNT; c.height = HEIGHT;
    const g = c.getContext('2d');
    g.fillStyle = color;
    glyphs.forEach((gl, i) => {
      gl.cols.forEach((col, x) => {
        for (let y = 0; y < HEIGHT; y++) if (col >> y & 1) g.fillRect(i * CELL + x, y, 1, 1);
      });
    });
    return atlases[color] = c;
  }
  function glyphOf(ch) {
    const i = ch.charCodeAt(0) - 32;
    return i >= 0 && i < COUNT ? i : 31; // unknown characters render as '?'
  }
  function width(text) {
    text = text == null ? '' : String(text);
    let w = 0;
    for (const ch of text) w += glyphs[glyphOf(ch)].w + 1;
    return w > 0 ? w - 1 : 0;
  }
  function draw(g, text, x, y, color = '#3a2414', scale = 1) {
    text = text == null ? '' : String(text); // never let a missing word stop the game
    const a = atlas(color);
    x = Math.round(x); y = Math.round(y);
    for (const ch of text) {
      const i = glyphOf(ch), gl = glyphs[i];
      if (i) g.drawImage(a, i * CELL + gl.a, 0, gl.w, HEIGHT, x, y, gl.w * scale, HEIGHT * scale);
      x += (gl.w + 1) * scale;
    }
  }
  function shadow(g, text, x, y, color = '#fff', shade = '#2a1a10', scale = 1) {
    draw(g, text, x + scale, y + scale, shade, scale);
    draw(g, text, x, y, color, scale);
  }
  function center(g, text, cx, y, color, scale = 1) { draw(g, text, cx - width(text) * scale / 2, y, color, scale); }
  function wrap(text, maxW) {
    const lines = [];
    for (const para of String(text).split('\n')) {
      let line = '';
      for (const word of para.split(' ')) {
        const test = line ? line + ' ' + word : word;
        if (width(test) > maxW && line) { lines.push(line); line = word; } else line = test;
      }
      lines.push(line);
    }
    return lines;
  }
  return { draw, shadow, center, wrap, width, HEIGHT };
})();
